// Measure how far the Kepler and Kepler+J2 propagators drift from SGP4 for
// every satellite in public/data/omm.json, and write docs/RESULTS.md.
//
// Run with `npm run compare`. Each satellite is propagated from its own
// element-set epoch, with 1-minute steps for 7 days.

import { readFileSync, writeFileSync } from 'node:fs';
import { CATALOG } from '../src/data/catalog.js';
import { parseOmm } from '../src/data/elements.js';
import { errorSeries, summarise, sgp4Reference } from '../src/analysis/compare.js';
import { findPasses } from '../src/passes/passes.js';
import { propagateKepler } from '../src/orbit/kepler.js';
import { propagateJ2 } from '../src/orbit/j2.js';
import { DEG } from '../src/orbit/constants.js';

const HOUR = 3600e3, DAY = 86400e3;
const HORIZONS = [0, HOUR, DAY, 7 * DAY];
const data = JSON.parse(readFileSync(new URL('../public/data/omm.json', import.meta.url), 'utf8'));

const fmt = (km) => (km < 10 ? km.toFixed(1) : Math.round(km).toLocaleString('en-GB'));
const rows = [];
const ric = [];
for (const omm of data.satellites) {
  const el = parseOmm(omm);
  const info = CATALOG.find((s) => s.noradId === el.noradId);
  const series = errorSeries(el, omm, 7 * DAY, 60e3);
  const s = summarise(series, HORIZONS);
  const name = info?.name ?? el.name;
  rows.push(`| ${name} | ${info?.orbit ?? ''} | ${s.map((x) => `${fmt(x.kepler)} / ${fmt(x.j2)}`).join(' | ')} |`);
  const day = series.find((r) => r.t === DAY);
  const comp = (m) => ['radial', 'along', 'cross'].map((k) => fmt(Math.abs(day[m][k]))).join(' / ');
  ric.push(`| ${name} | ${comp('kepler')} | ${comp('j2')} |`);
}

// ---- Pass predictions vs Heavens-Above (frozen ISS fixture, same element set)
const read = (path) => JSON.parse(readFileSync(new URL(path, import.meta.url), 'utf8'));
const ha = read('../tests/fixtures/heavens-above-iss-bengaluru.json');
const issOmm = read('../tests/fixtures/iss-omm.json');
const iss = parseOmm(issOmm);
const sgp4 = sgp4Reference(issOmm);
const obs = { lat: ha.observer.latDeg * DEG, lon: ha.observer.lonDeg * DEG, height: ha.observer.heightM / 1000 };
const passRows = [];
for (const [label, propagate] of [['SGP4 (satellite.js) + this project\'s pass search and frames', (_, t) => sgp4(t)], ['This project\'s Kepler + J2 propagator', propagateJ2], ['This project\'s pure Kepler propagator', propagateKepler]]) {
  const { passes } = findPasses(iss, obs, { start: Date.parse('2026-10-10T00:00:00Z'), end: Date.parse('2026-10-20T00:00:00Z'), minElevationDeg: 10, propagate });
  const diffs = ha.passes.map((h) => {
    const p = passes.find((x) => Math.abs(x.max.t - Date.parse(h.max)) < 15 * 60e3);
    if (!p) return null;
    return { dt: Math.max(...[p.rise.t - Date.parse(h.start), p.max.t - Date.parse(h.max), p.set.t - Date.parse(h.end)].map((x) => Math.abs(x) / 1000)), dAlt: Math.abs(p.max.elDeg - h.maxAltDeg), day: h.max.slice(0, 10) };
  });
  const found = diffs.filter(Boolean);
  const within = found.filter((d) => d.dt <= 60).length;
  const day1 = found.filter((d) => d.day === '2026-10-10');
  const last = found.filter((d) => d.day === '2026-10-19');
  const worst = (arr) => (arr.length ? `${Math.round(Math.max(...arr.map((d) => d.dt)))} s` : 'n/a');
  passRows.push(`| ${label} | ${found.length} / ${ha.passes.length} | ${within} / ${ha.passes.length} | ${worst(day1)} | ${worst(last)} | ${found.length ? Math.max(...found.map((d) => d.dAlt)).toFixed(1) + '°' : 'n/a'} |`);
}

const md = `# Results: two-body propagator vs SGP4

Generated by \`npm run compare\` from the element sets fetched ${data.fetchedAt.slice(0, 10)}.
Each satellite is propagated from its own element-set epoch. The reference is SGP4
([satellite.js](https://github.com/shashwatak/satellite-js)), the model these elements were fitted for.

**SGP4 is the yardstick here, not the truth.** It is itself typically ~1 km off at
epoch and drifts by a few km per day for low orbits, so these numbers say how well this
project's propagators use the elements, not how close they are to where the satellite really is.

## Position error vs SGP4 (km)

Worst error within each window, sampled every minute. Each cell is **Kepler / Kepler + J2**.

| Satellite | Orbit | At epoch | 1 hour | 1 day | 1 week |
|---|---|---|---|---|---|
${rows.join('\n')}

## Where the error is after 1 day (km)

Split into radial / along-track / cross-track, relative to the SGP4 position.

| Satellite | Kepler (R / I / C) | Kepler + J2 (R / I / C) |
|---|---|---|
${ric.join('\n')}

## What the numbers show

- **Pure Kepler is unusable after a few hours in low orbit.** After one day it is
  400–900 km off. The cross-track part comes from the orbit plane drifting (the ISS's plane turns
  ~5°/day); the along-track part comes from the orbital period and perigee drift that J2 causes.
- **Adding J2's secular drift closes over 95% of that gap for low orbits**, down to
  roughly 12–19 km after one day. The J2 rates agree with SGP4's own internal rates to within
  0.1–0.7%.
- **The error at epoch (3–28 km) isn't fixed by J2.** Published elements are *mean*
  elements: averages with SGP4's short-period wobbles (a few km within each orbit)
  removed. SGP4 adds those wobbles back; these models don't.
- **The ISS's remaining error is drag.** It is almost entirely along-track and grows like t².
  The element set's own ṅ/2 field predicts ≈135 km after 7 days; measured: ≈150 km.
- **At epoch, the J2 model is sometimes a few km *worse* than plain Kepler** (e.g. ASTROSAT
  3.4 vs 9.4 km). It uses SGP4's corrected (Brouwer) semi-major axis, which differs from the
  plain one by 0.5 km (ISS) to 6.2 km (ASTROSAT), depending on inclination. In SGP4 the short-period terms not modelled here partly offset
  that. Over any window longer than an hour, the corrected value wins clearly.
- **For geosynchronous orbits the picture is mixed.** J2 helps IRNSS-1I over a week
  (60 → 38 km) but makes INSAT-3DR worse (27 → 50 km). At 42,000 km J2 is weak, and SGP4's
  deep-space mode also models the Sun's and Moon's gravity and resonance with Earth's slightly
  oval equator. These models have neither. Both models stay within ~60 km of SGP4 for these orbits
  over a week. The J2 rates for these satellites match SGP4's to 4 decimal places, so this is
  missing physics, not a bug.

## Pass predictions vs Heavens-Above

27 ISS passes over Bengaluru (12.9716°N, 77.5946°E, 920 m), 10–20 October 2026, retrieved from
[Heavens-Above](https://www.heavens-above.com) on 2026-10-10. Heavens-Above used the same element
set (epoch 9 October). Its start and end times are when the ISS crosses 10° elevation, so mine use
10° too. Each pass's error is the worst of its rise, highest-point and set time differences.

| Propagator | Passes found | Within 1 minute | Worst error, day 1 | Worst error, day 10 | Worst max-elevation difference |
|---|---|---|---|---|---|
${passRows.join('\n')}

- **The first row tests everything except this project's propagator.** Heavens-Above uses SGP4 too, so
  running this project's pass search, sidereal time, frame conversions and look angles on SGP4 positions
  should reproduce its list exactly, and it does (within 1 s; elevation differences are
  Heavens-Above rounding to whole degrees).
- **With the J2 propagator, every pass is within a minute for all 10 days.** The error grows from
  1–2 s on day 1 to about 40 s on day 10. That is the drag-driven along-track drift above: the
  ISS moves 7.7 km/s, so 150 km along-track is about 20 s. Pass times are forgiving of position
  errors that look large in kilometres.
- **Pure Kepler misses 19 of the 27 passes** (they happen at a different time, or not at all, in its
  model), and gets only 5 within a minute.

## Limitations of this comparison

- Errors are measured from each element set's epoch. In the app, positions are predicted
  from data that is already hours or days old, so real-world error is larger.
- One snapshot of elements per satellite. A fuller study would repeat this over many element
  sets and dates.
- No comparison against true positions (e.g. GPS-derived ISS ephemerides) yet.
`;
writeFileSync(new URL('../docs/RESULTS.md', import.meta.url), md);
console.log(md);
